//! The Bazel preset in a consumer workspace: `.dx/bazelrc/*.bazelrc` imported from the root `.bazelrc`.
//!
//! One reader ([`inspect_preset`]) feeds init, status and upgrade, so they agree.

use std::path::{Path, PathBuf};

use crate::error::AdoptError;
use crate::preset_fragment::{
    bazelrc_imports, is_generated, layer_import_state, layer_is_current, migrate_layer_imports,
    owned_collisions_in_content, prepend_imports, render_all, render_layer, ImportState, Layer,
    CONSUMER_DIR, REPO_DIR,
};
use crate::scaffold::{scaffold_dest_within_root, Applied};

/// The root `.bazelrc` file.
pub const BAZELRC: &str = ".bazelrc";

/// The root `.gitignore` file.
pub const GITIGNORE: &str = ".gitignore";

/// The line `.gitignore` needs so the generated layers stay out of git.
pub const LAYERS_IGNORE: &str = "/.dx/bazelrc/";

const COVERING_LINES: [&str; 8] = [
    "/.dx/bazelrc/",
    "/.dx/bazelrc",
    ".dx/bazelrc/",
    ".dx/bazelrc",
    "/.dx/",
    "/.dx",
    ".dx/",
    ".dx",
];

/// What one layer file under `.dx/bazelrc` holds.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum LayerFile {
    Current,
    /// Generated by dx but different from what this dx renders.
    Stale,
    Missing,
    /// Present without the dx header, so it belongs to the project.
    Custom,
    Symlink,
}

/// A workspace's preset: the root `.bazelrc` imports and the layer files.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PresetState {
    /// False when the workspace keeps the preset in `tools/bazelrc` (rules_dx itself).
    pub applicable: bool,
    /// The root `.bazelrc` text, empty when missing.
    pub rc_text: String,
    pub rc_exists: bool,
    pub rc_symlink: bool,
    /// The `.bazelrc` text with old `import` layer lines changed to `try-import`, when any exist.
    pub migrated_rc: Option<String>,
    /// The `.gitignore` text with the layers line added, when the file exists and lacks it.
    pub migrated_ignore: Option<String>,
    /// Owned preset lines the root `.bazelrc` repeats.
    pub collisions: Vec<String>,
    pub layers: Vec<(Layer, ImportState, LayerFile)>,
}

impl PresetState {
    /// True when no line, active or commented, names a `.dx/bazelrc` layer.
    pub fn unwired(&self) -> bool {
        self.layers
            .iter()
            .all(|(_, import, _)| *import == ImportState::Absent)
    }

    /// Whether apply would change old `import` lines to `try-import`.
    pub fn will_migrate_rc(&self) -> bool {
        self.applicable && !self.rc_symlink && self.migrated_rc.is_some()
    }

    /// Whether apply would add the layers line to `.gitignore`.
    pub fn will_migrate_ignore(&self) -> bool {
        self.applicable && self.migrated_ignore.is_some() && (!self.unwired() || self.will_import())
    }

    /// Whether apply would add the import block.
    pub fn will_import(&self) -> bool {
        self.applicable && self.unwired() && !self.rc_symlink && self.collisions.is_empty()
    }

    /// Some layers are named in the `.bazelrc` and some are not.
    pub fn partial(&self) -> bool {
        !self.unwired()
            && self
                .layers
                .iter()
                .any(|(_, import, _)| *import == ImportState::Absent)
    }

    /// Whether the layer is, or after apply will be, imported.
    fn managed(&self, import: ImportState) -> bool {
        import == ImportState::Active || (import == ImportState::Absent && self.will_import())
    }

    /// The layers apply would create or rewrite, as `(layer, is_create)`.
    fn to_write(&self) -> Vec<(Layer, bool)> {
        if !self.applicable {
            return Vec::new();
        }
        self.layers
            .iter()
            .filter(|(_, import, _)| self.managed(*import))
            .filter_map(|(layer, _, file)| match file {
                LayerFile::Missing => Some((*layer, true)),
                LayerFile::Stale => Some((*layer, false)),
                _ => None,
            })
            .collect()
    }

    /// Advisories for what apply leaves alone.
    pub fn notes(&self) -> Vec<String> {
        let mut notes = Vec::new();
        if !self.applicable {
            return notes;
        }
        if self.unwired() {
            if self.rc_symlink {
                notes.push(format!(
                    "{BAZELRC} is a symlink; add these imports yourself: {}",
                    self.import_lines().join("; ")
                ));
            } else if !self.collisions.is_empty() {
                notes.push(
                    dx_preset::PresetError::OwnedCollision {
                        lines: self.collisions.join(", "),
                    }
                    .to_string()
                        + "; preset imports not added",
                );
            }
        } else if self.partial() {
            let absent: Vec<_> = self
                .layers
                .iter()
                .filter(|(_, import, _)| *import == ImportState::Absent)
                .map(|(layer, ..)| layer.file_name())
                .collect();
            notes.push(format!(
                "{BAZELRC} does not import {}; add the import or comment it out to opt out",
                absent.join(", ")
            ));
        }
        for (layer, import, file) in &self.layers {
            if !self.managed(*import) {
                continue;
            }
            let rel = layer_rel(*layer);
            match file {
                LayerFile::Custom => notes.push(format!(
                    "{rel} exists without the dx header and is left untouched"
                )),
                LayerFile::Symlink => {
                    notes.push(format!("{rel} is a symlink and is left untouched"))
                }
                _ => {}
            }
        }
        notes
    }

    fn import_lines(&self) -> Vec<String> {
        Layer::ALL
            .iter()
            .map(|layer| dx_preset::import_line(CONSUMER_DIR, *layer))
            .collect()
    }
}

/// The workspace-relative path of one layer file.
pub fn layer_rel(layer: Layer) -> String {
    format!("{CONSUMER_DIR}/{}", layer.file_name())
}

/// Every workspace-relative path the preset owns.
pub fn preset_paths() -> Vec<String> {
    let mut paths = vec![BAZELRC.to_owned(), GITIGNORE.to_owned()];
    paths.extend(Layer::ALL.iter().map(|layer| layer_rel(*layer)));
    paths
}

fn read_text(path: &Path, rel: &str) -> Result<Option<String>, AdoptError> {
    match std::fs::read_to_string(path) {
        Ok(text) => Ok(Some(text)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(AdoptError::ReadFile {
            path: rel.to_owned(),
            detail: e.to_string(),
        }),
    }
}

fn layer_file(root: &Path, layer: Layer) -> LayerFile {
    let path = root.join(layer_rel(layer));
    let Ok(meta) = std::fs::symlink_metadata(&path) else {
        return LayerFile::Missing;
    };
    if meta.file_type().is_symlink() {
        return LayerFile::Symlink;
    }
    match std::fs::read_to_string(&path) {
        Ok(text) if layer_is_current(&text, layer) => LayerFile::Current,
        Ok(text) if is_generated(&text) => LayerFile::Stale,
        _ => LayerFile::Custom,
    }
}

/// Reads the preset state of `root` once.
pub fn inspect_preset(root: &Path) -> Result<PresetState, AdoptError> {
    let rc_path = root.join(BAZELRC);
    let rc_symlink = std::fs::symlink_metadata(&rc_path).is_ok_and(|m| m.file_type().is_symlink());
    let text = read_text(&rc_path, BAZELRC)?;
    let rc_exists = text.is_some();
    let rc_text = text.unwrap_or_default();
    let repo_prefix = format!("{REPO_DIR}/");
    let applicable = !bazelrc_imports(&rc_text)
        .iter()
        .any(|rel| rel.starts_with(&repo_prefix));
    let migrated_rc = migrate_layer_imports(&rc_text, CONSUMER_DIR);
    let migrated_ignore = ignore_with_layers(read_text(&root.join(GITIGNORE), GITIGNORE)?);
    let layers = layer_import_state(&rc_text, CONSUMER_DIR)
        .into_iter()
        .map(|(layer, import)| (layer, import, layer_file(root, layer)))
        .collect();
    Ok(PresetState {
        applicable,
        collisions: owned_collisions_in_content(&rc_text, &render_all()),
        rc_text,
        rc_exists,
        rc_symlink,
        migrated_rc,
        migrated_ignore,
        layers,
    })
}

fn ignore_with_layers(text: Option<String>) -> Option<String> {
    let mut text = text?;
    if text
        .lines()
        .any(|line| COVERING_LINES.contains(&line.trim()))
    {
        return None;
    }
    let eol = if text.contains("\r\n") { "\r\n" } else { "\n" };
    if !text.is_empty() && !text.ends_with('\n') {
        text.push_str(eol);
    }
    text.push_str(LAYERS_IGNORE);
    text.push_str(eol);
    Some(text)
}

/// Whether git lists files under `.dx/bazelrc`; false when git is missing or this is no repository.
fn layers_tracked(root: &Path) -> bool {
    std::process::Command::new("git")
        .args(["ls-files", "--", CONSUMER_DIR])
        .current_dir(root)
        .output()
        .is_ok_and(|out| out.status.success() && !out.stdout.is_empty())
}

fn tracked_note() -> String {
    format!(
        "{CONSUMER_DIR} is committed; run `git rm --cached -r {CONSUMER_DIR}` to stop tracking it"
    )
}

fn write(root: &Path, rel: &str, content: &str) -> Result<PathBuf, AdoptError> {
    let dest = scaffold_dest_within_root(root, rel)?;
    if let Some(parent) = dest.parent() {
        std::fs::create_dir_all(parent).map_err(|e| AdoptError::CreateParent {
            parent: parent.display().to_string(),
            detail: e.to_string(),
        })?;
    }
    dx_atomic_fs::write_atomic(&dest, content.as_bytes()).map_err(|e| AdoptError::WriteFile {
        path: dest.display().to_string(),
        detail: e.to_string(),
    })?;
    Ok(dest)
}

/// Fails before any write when a preset destination escapes the workspace.
pub fn preflight_preset(root: &Path) -> Result<(), AdoptError> {
    inspect_preset(root)?;
    scaffold_dest_within_root(root, BAZELRC)?;
    for layer in Layer::ALL {
        scaffold_dest_within_root(root, &layer_rel(layer))?;
    }
    Ok(())
}

/// Creates or rewrites the layer files and adds the import block when that is safe.
///
/// Paths written land in `applied`; advisories land in `notes`.
pub fn write_preset(
    root: &Path,
    applied: &mut Applied,
    notes: &mut Vec<String>,
) -> Result<(), AdoptError> {
    let state = inspect_preset(root)?;
    if !state.applicable {
        return Ok(());
    }
    notes.extend(state.notes());
    if !state.to_write().is_empty() {
        let pin = std::fs::read_to_string(root.join(".bazelversion")).unwrap_or_default();
        notes.extend(crate::status::old_pin_note(&pin));
    }
    for (layer, _) in state.to_write() {
        let rel = layer_rel(layer);
        write(root, &rel, &render_layer(layer))?;
        applied.wrote.push(rel);
    }
    if state.will_import() {
        let text = prepend_imports(&state.rc_text, CONSUMER_DIR, &Layer::ALL);
        write(root, BAZELRC, &text)?;
        applied.wrote.push(BAZELRC.to_owned());
    } else if let (true, Some(text)) = (state.will_migrate_rc(), &state.migrated_rc) {
        write(root, BAZELRC, text)?;
        applied.wrote.push(BAZELRC.to_owned());
    }
    if let (true, Some(text)) = (state.will_migrate_ignore(), &state.migrated_ignore) {
        write(root, GITIGNORE, text)?;
        applied.wrote.push(GITIGNORE.to_owned());
    }
    if layers_tracked(root) {
        notes.push(tracked_note());
    }
    Ok(())
}

/// Writes imported layers that are missing or stale; never edits `.bazelrc` or a custom file.
///
/// Returns the written paths.
pub fn sync_preset(root: &Path) -> Result<Vec<String>, AdoptError> {
    let state = inspect_preset(root)?;
    if !state.applicable {
        return Ok(Vec::new());
    }
    let mut wrote = Vec::new();
    for (layer, import, file) in &state.layers {
        if *import == ImportState::Active && matches!(file, LayerFile::Missing | LayerFile::Stale) {
            let rel = layer_rel(*layer);
            write(root, &rel, &render_layer(*layer))?;
            wrote.push(rel);
        }
    }
    Ok(wrote)
}

/// What a workspace lacks against what [`write_preset`] writes.
#[derive(Debug, Default, PartialEq, Eq)]
pub struct PresetDrift {
    pub missing: Vec<String>,
    pub stale: Vec<String>,
    pub other: Vec<String>,
}

/// The preset drift under `root`, without writing.
pub fn preset_drift(root: &Path) -> PresetDrift {
    let mut drift = PresetDrift::default();
    let state = match inspect_preset(root) {
        Ok(state) => state,
        Err(error) => {
            drift.other.push(error.to_string());
            return drift;
        }
    };
    if !state.applicable {
        return drift;
    }
    drift.other.extend(state.notes());
    if state.will_import() {
        if state.rc_exists {
            drift.stale.push(BAZELRC.to_owned());
        } else {
            drift.missing.push(BAZELRC.to_owned());
        }
    } else if state.will_migrate_rc() {
        drift.stale.push(BAZELRC.to_owned());
    }
    if state.will_migrate_ignore() {
        drift.stale.push(GITIGNORE.to_owned());
    }
    if layers_tracked(root) {
        drift.other.push(tracked_note());
    }
    drift
}

#[cfg(test)]
mod tests {
    use super::*;

    fn apply(root: &Path) -> (Vec<String>, Vec<String>) {
        let (mut applied, mut notes) = (Applied::default(), Vec::new());
        write_preset(root, &mut applied, &mut notes).expect("write");
        (applied.wrote, notes)
    }

    #[test]
    fn empty_dir_gets_layers_and_imports_then_nothing() {
        let scratch = dx_test_scratch::scratch("dx-preset-empty-");
        let root = scratch.path();
        let (wrote, notes) = apply(root);
        assert_eq!(wrote.len(), Layer::ALL.len() + 1);
        assert!(notes.is_empty());
        assert_eq!(preset_drift(root), PresetDrift::default());
        let (wrote, notes) = apply(root);
        assert!(wrote.is_empty() && notes.is_empty(), "{wrote:?} {notes:?}");
    }

    #[test]
    fn existing_bazelrc_keeps_its_bytes_below_the_block() {
        let scratch = dx_test_scratch::scratch("dx-preset-rc-");
        let root = scratch.path();
        std::fs::write(root.join(".bazelrc"), "build --jobs=2\r\n").expect("rc");
        apply(root);
        let text = std::fs::read_to_string(root.join(".bazelrc")).expect("read");
        assert!(text.ends_with("\r\n\r\nbuild --jobs=2\r\n"), "{text:?}");
        assert!(text.starts_with(dx_preset::IMPORT_COMMENT));
    }

    #[test]
    fn collision_and_symlinked_rc_add_no_import() {
        let scratch = dx_test_scratch::scratch("dx-preset-collide-");
        let root = scratch.path();
        std::fs::write(root.join(".bazelrc"), "build --verbose_failures\n").expect("rc");
        let (wrote, notes) = apply(root);
        assert!(wrote.is_empty());
        assert!(notes[0].contains("duplicates preset lines"), "{notes:?}");
        assert_eq!(
            std::fs::read_to_string(root.join(".bazelrc")).expect("read"),
            "build --verbose_failures\n"
        );
        #[cfg(unix)]
        {
            let other = tempdir_sibling(root);
            std::fs::write(&other, "").expect("target");
            std::fs::remove_file(root.join(".bazelrc")).expect("rm");
            std::os::unix::fs::symlink(&other, root.join(".bazelrc")).expect("link");
            let (wrote, notes) = apply(root);
            assert!(wrote.is_empty());
            assert!(notes[0].contains("symlink"), "{notes:?}");
        }
    }

    #[cfg(unix)]
    fn tempdir_sibling(root: &Path) -> PathBuf {
        root.join("real.bazelrc")
    }

    #[test]
    fn headerless_layer_is_left_alone_and_stale_is_rewritten() {
        let scratch = dx_test_scratch::scratch("dx-preset-custom-");
        let root = scratch.path();
        apply(root);
        let correctness = root.join(layer_rel(Layer::Correctness));
        std::fs::write(&correctness, "build --mine\n").expect("custom");
        let performance = root.join(layer_rel(Layer::Performance));
        std::fs::write(&performance, format!("{}old\n", dx_preset::HEADER_MARKER)).expect("stale");
        let drift = preset_drift(root);
        assert!(drift.other[0].contains("without the dx header"));
        let (wrote, _) = apply(root);
        assert_eq!(wrote, vec![layer_rel(Layer::Performance)]);
        assert_eq!(
            std::fs::read_to_string(&correctness).expect("read"),
            "build --mine\n"
        );
    }

    #[test]
    fn commented_import_opts_a_layer_out_and_unlisted_one_is_noted() {
        let scratch = dx_test_scratch::scratch("dx-preset-optout-");
        let root = scratch.path();
        apply(root);
        let resources = dx_preset::import_line(CONSUMER_DIR, Layer::Resources);
        let rc = std::fs::read_to_string(root.join(".bazelrc")).expect("rc");
        std::fs::remove_file(root.join(layer_rel(Layer::Resources))).expect("rm");
        std::fs::write(
            root.join(".bazelrc"),
            rc.replace(&resources, &format!("# {resources}")),
        )
        .expect("comment");
        assert_eq!(preset_drift(root), PresetDrift::default());
        assert!(apply(root).0.is_empty());
        assert!(sync_preset(root).expect("sync").is_empty());
        assert!(!root.join(layer_rel(Layer::Resources)).exists());
        std::fs::write(
            root.join(".bazelrc"),
            rc.replace(&format!("{resources}\n"), ""),
        )
        .expect("delete");
        let drift = preset_drift(root);
        assert!(drift.other[0].contains("resources.bazelrc"), "{drift:?}");
        assert!(apply(root).0.is_empty());
    }

    #[test]
    fn sync_rewrites_missing_and_stale_and_repo_layout_is_skipped() {
        let scratch = dx_test_scratch::scratch("dx-preset-sync-");
        let root = scratch.path();
        assert!(sync_preset(root).expect("sync").is_empty());
        assert!(!root.join(CONSUMER_DIR).exists());
        apply(root);
        assert!(sync_preset(root).expect("sync").is_empty());
        let path = root.join(layer_rel(Layer::Resources));
        std::fs::write(&path, format!("{}old\n", dx_preset::HEADER_MARKER)).expect("stale");
        assert_eq!(
            sync_preset(root).expect("sync"),
            vec![layer_rel(Layer::Resources)]
        );
        std::fs::remove_file(&path).expect("rm");
        assert_eq!(
            sync_preset(root).expect("sync"),
            vec![layer_rel(Layer::Resources)]
        );
        assert!(path.is_file());
        let repo = dx_test_scratch::scratch("dx-preset-repo-");
        let imports: Vec<_> = Layer::ALL
            .iter()
            .map(|layer| dx_preset::import_line(REPO_DIR, *layer))
            .collect();
        std::fs::write(repo.path().join(".bazelrc"), imports.join("\n")).expect("rc");
        assert!(!inspect_preset(repo.path()).expect("inspect").applicable);
        assert!(apply(repo.path()).0.is_empty());
    }

    #[test]
    fn old_layout_moves_in_one_apply_and_keeps_user_lines() {
        let scratch = dx_test_scratch::scratch("dx-preset-old-");
        let root = scratch.path();
        apply(root);
        let old: String = Layer::ALL
            .iter()
            .map(|layer| format!("import %workspace%/{CONSUMER_DIR}/{}\n", layer.file_name()))
            .collect();
        std::fs::write(root.join(".bazelrc"), format!("{old}build --jobs=2\n")).expect("rc");
        std::fs::write(root.join(".gitignore"), "target/\nmine.log").expect("ignore");
        let drift = preset_drift(root);
        assert_eq!(drift.stale, vec![BAZELRC, GITIGNORE]);
        let (wrote, _) = apply(root);
        assert_eq!(wrote, vec![BAZELRC, GITIGNORE]);
        let rc = std::fs::read_to_string(root.join(".bazelrc")).expect("rc");
        assert_eq!(
            rc,
            format!("{}build --jobs=2\n", old.replace("import", "try-import"))
        );
        let ignore = std::fs::read_to_string(root.join(".gitignore")).expect("ignore");
        assert_eq!(ignore, "target/\nmine.log\n/.dx/bazelrc/\n");
        assert_eq!(preset_drift(root), PresetDrift::default());
        assert!(apply(root).0.is_empty());
    }

    #[test]
    fn covering_ignore_line_is_enough() {
        for line in [".dx/", "/.dx/bazelrc"] {
            assert_eq!(
                ignore_with_layers(Some(format!("{line}\n"))),
                None,
                "{line}"
            );
        }
        assert_eq!(ignore_with_layers(None), None);
    }

    fn git(root: &Path, sandbox: &Path, args: &[&str]) {
        let mut cmd = std::process::Command::new("git");
        cmd.arg("-C").arg(root).args(args);
        dx_test_scratch::isolate_git(&mut cmd, sandbox);
        assert!(cmd.status().expect("git").success(), "{args:?}");
    }

    #[test]
    fn tracked_layers_get_the_git_rm_note() {
        let scratch = dx_test_scratch::scratch("dx-preset-tracked-");
        let root = scratch.path().join("repo");
        std::fs::create_dir_all(&root).expect("dir");
        git(&root, scratch.path(), &["init", "-q"]);
        apply(&root);
        git(&root, scratch.path(), &["add", "-f", CONSUMER_DIR]);
        assert!(preset_drift(&root).other.contains(&tracked_note()));
        assert!(apply(&root).1.contains(&tracked_note()));
    }
}
