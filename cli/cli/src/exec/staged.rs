//! Runs a staged generator (paket2bazel, go) on copies of a set's inputs in a scratch
//! directory and reports which declared locks it would change. The caller decides what
//! to do with the result, so `dx update` and `dx bump` share the same checks.

use dx_update::backend::StagedRun;
use std::collections::BTreeMap;

/// A scratch directory outside the workspace, removed on every path.
pub(super) struct Scratch(pub(super) std::path::PathBuf);

impl Scratch {
    pub(super) fn create(label: &str) -> std::io::Result<Scratch> {
        static NEXT: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
        let n = NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        let safe: String = label
            .chars()
            .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
            .collect();
        let dir = std::env::temp_dir().join(format!("dx-staged-{}-{n}-{safe}", std::process::id()));
        std::fs::create_dir(&dir)?;
        let scratch = Scratch(dir);
        std::fs::create_dir(scratch.0.join("out"))?;
        Ok(scratch)
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        remove_tree(&self.0);
    }
}

/// Removes a scratch tree, making read-only entries writable and retrying once
/// (a go module cache is read-only unless it was created with `-modcacherw`).
fn remove_tree(dir: &std::path::Path) {
    if std::fs::remove_dir_all(dir).is_ok() {
        return;
    }
    fn open_up(dir: &std::path::Path) {
        let Ok(entries) = std::fs::read_dir(dir) else {
            return;
        };
        for entry in entries.flatten() {
            let path = entry.path();
            let Ok(meta) = std::fs::symlink_metadata(&path) else {
                continue;
            };
            if meta.is_dir() {
                let mut permissions = meta.permissions();
                #[allow(clippy::permissions_set_readonly_false)]
                permissions.set_readonly(false);
                #[cfg(unix)]
                {
                    use std::os::unix::fs::PermissionsExt;
                    permissions.set_mode(0o700);
                }
                let _ = std::fs::set_permissions(&path, permissions);
                open_up(&path);
            }
        }
    }
    if let Ok(meta) = std::fs::metadata(dir) {
        let _ = std::fs::set_permissions(dir, meta.permissions());
    }
    open_up(dir);
    let _ = std::fs::remove_dir_all(dir);
}

pub(super) fn file_name(rel: &str) -> &str {
    rel.rsplit('/').next().unwrap_or(rel)
}

/// What launching the tool did: how it ended and which guarded files it wrote.
pub(super) struct ToolRun {
    pub(super) launched: std::io::Result<dx_process::ChildStatus>,
    /// Declared files the tool wrote in the workspace (restored by the caller).
    pub(super) wrote: Option<Vec<String>>,
}

/// Why a staged run did not produce a comparable result.
pub(super) enum StagedError {
    Failed {
        message: String,
        /// Typed failure code; `None` falls back to `update_failed`.
        code: Option<&'static str>,
    },
    /// The caller's gate stopped the run with this exit code.
    Exit(i32),
}

/// Launches the staged tool: gate, guard and process live behind it.
pub(super) type LaunchTool<'a> =
    dyn FnMut(&[String], &[(String, String)]) -> Result<ToolRun, i32> + 'a;

/// A declared lock whose generated bytes differ from the workspace.
pub(super) type Differing = (String, Vec<u8>);

/// Stages `run`'s inputs, launches it through `launch` (which receives the argv and env and
/// owns the gate, the check guard and the process) and returns the locks that differ.
/// An empty result means every declared lock is already current.
pub(super) fn run_staged_core(
    run: &StagedRun,
    workspace: &std::path::Path,
    name: &str,
    verb: &str,
    launch: &mut LaunchTool<'_>,
) -> Result<Vec<Differing>, StagedError> {
    macro_rules! fail {
        ($($arg:tt)*) => {
            return Err(StagedError::Failed {
                message: format!("failed to {verb} {name}: {}", format!($($arg)*)),
                code: None,
            })
        };
    }

    let scratch = match Scratch::create(name) {
        Ok(scratch) => scratch,
        Err(error) => fail!("cannot create scratch directory: {error}"),
    };
    let inputs_dir = run.inputs_dir(&scratch.0);
    let mut staged_inputs: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    for rel in &run.inputs {
        let copied = dx_path::workspace::resolve_target_in_workspace(workspace, rel)
            .and_then(std::fs::read)
            .and_then(|bytes| {
                std::fs::write(inputs_dir.join(file_name(rel)), &bytes)?;
                if inputs_dir != scratch.0 {
                    staged_inputs.insert(file_name(rel).to_owned(), bytes);
                }
                Ok(())
            });
        if let Err(error) = copied {
            fail!("cannot stage {rel}: {error}");
        }
    }
    let argv = run.argv(&scratch.0);
    let ran = launch(&argv, &run.env(&scratch.0)).map_err(StagedError::Exit)?;
    if let Some(wrote) = ran.wrote {
        return Err(StagedError::Failed {
            message: format!(
                "failed to {verb} {name}: check_wrote: {} (restored); {} must only write into its scratch output folder",
                wrote.join(", "),
                run.tool_name()
            ),
            code: Some("check_wrote"),
        });
    }
    match ran.launched {
        Err(error) => fail!("failed to launch updater: {error}"),
        Ok(status) => match status.code {
            Some(0) => {}
            Some(code) => fail!("updater exited {code}"),
            None => fail!("updater terminated by signal"),
        },
    }
    let mut generated: BTreeMap<String, Vec<u8>> = BTreeMap::new();
    match std::fs::read_dir(scratch.0.join("out")) {
        Ok(entries) => {
            for entry in entries.flatten() {
                let name = entry.file_name().to_string_lossy().into_owned();
                match std::fs::read(entry.path()) {
                    Ok(bytes) => {
                        generated.insert(name, bytes);
                    }
                    Err(error) => {
                        fail!("cannot read generated {name}: {error}");
                    }
                }
            }
        }
        Err(error) => {
            fail!("cannot read generated files: {error}");
        }
    }
    let declared: BTreeMap<&str, &String> = run
        .outputs
        .iter()
        .map(|rel| (file_name(rel), rel))
        .collect();
    // An input the tool left as it found it is not output; a changed one that is not a
    // declared lock means the tool edited a manifest.
    let mut changed_inputs: Vec<String> = Vec::new();
    generated.retain(|name, bytes| match staged_inputs.get(name) {
        Some(original) if !declared.contains_key(name.as_str()) => {
            if original != bytes {
                changed_inputs.push(name.clone());
            }
            false
        }
        _ => true,
    });
    if !changed_inputs.is_empty() {
        let names = changed_inputs.join(", ");
        fail!(
            "{} changed {names}; dx writes only declared locks",
            run.tool_name()
        );
    }
    let undeclared: Vec<&str> = generated
        .keys()
        .map(String::as_str)
        .filter(|name| !declared.contains_key(name))
        .collect();
    if !undeclared.is_empty() {
        fail!(
            "{} generated files not declared in locks: {}; list them in the set's locks",
            run.tool_name(),
            undeclared.join(", ")
        );
    }
    let missing: Vec<&str> = declared
        .iter()
        .filter(|(name, _)| !generated.contains_key(**name))
        .map(|(_, rel)| rel.as_str())
        .collect();
    if !missing.is_empty() {
        fail!(
            "{} did not generate declared locks: {}",
            run.tool_name(),
            missing.join(", ")
        );
    }
    let mut differing: Vec<Differing> = Vec::new();
    for (name, rel) in &declared {
        let bytes = &generated[*name];
        let current = dx_path::workspace::resolve_target_in_workspace(workspace, rel)
            .and_then(std::fs::read)
            .ok();
        if current.as_ref() != Some(bytes) {
            differing.push(((*rel).clone(), bytes.clone()));
        }
    }
    Ok(differing)
}

/// Writes each differing lock into the workspace. The error is the failure detail.
pub(super) fn write_outputs(
    workspace: &std::path::Path,
    differing: Vec<Differing>,
) -> Result<(), String> {
    for (rel, bytes) in differing {
        let path = match dx_path::workspace::resolve_target_in_workspace(workspace, &rel) {
            Ok(path) => path,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
                let (parent, name) = rel.rsplit_once('/').unwrap_or((".", &rel));
                match dx_path::workspace::resolve_target_in_workspace(workspace, parent) {
                    Ok(parent) => parent.join(name),
                    Err(error) => return Err(format!("cannot write {rel}: {error}")),
                }
            }
            Err(error) => return Err(format!("cannot write {rel}: {error}")),
        };
        if let Err(error) = dx_atomic_fs::write_atomic(&path, &bytes) {
            return Err(format!("cannot write {rel}: {error}"));
        }
    }
    Ok(())
}
