use std::collections::{BTreeMap, BTreeSet};
use std::process::Command;

use crate::{GenerateError, Inputs, RootBuild, render};

fn inputs(toml: Option<&str>, families: &[&str], root_files: &[&str]) -> Inputs {
    Inputs {
        config: toml.map(|text| dx_config::config::parse(text).expect("valid dx.toml")),
        repo: "rules_dx".to_owned(),
        root_files: root_files.iter().map(|file| (*file).to_owned()).collect(),
        root_build: Some(RootBuild {
            name: "BUILD.bazel".to_owned(),
            text: "exports_files([\"README.md\"])\n".to_owned(),
        }),
        root_texts: BTreeMap::new(),
        files: BTreeSet::new(),
        families: families.iter().map(|family| (*family).to_owned()).collect(),
    }
}

fn text(out: &BTreeMap<String, Vec<u8>>, path: &str) -> String {
    String::from_utf8(out[path].clone()).expect("utf-8")
}

/// The rendered tree in one string: base files by the tier they copy, rc files without the preset
/// every rc starts with.
fn summary(out: &BTreeMap<String, Vec<u8>>) -> String {
    let mut lines = String::new();
    for (path, bytes) in out {
        let text = String::from_utf8(bytes.clone()).expect("utf-8");
        lines.push_str(&format!("== {path}\n"));
        if let Some(base) = path.strip_prefix(".dx/config/") {
            let dir = base.split('/').next().expect("tool dir");
            if dir == "gitleaks" {
                lines.push_str("<standard and strict tier>\n");
                continue;
            }
            let config = crate::tools_gen::TOOL_CONFIGS
                .iter()
                .find(|config| {
                    config.tier_dir == dir || (config.tier_dir.is_empty() && config.id == dir)
                })
                .expect("a base belongs to a tool");
            let tier = match (text == config.standard, text == config.strict) {
                (true, true) => "standard and strict",
                (true, false) => "standard",
                (false, true) => "strict",
                (false, false) => panic!("{path} is not a tier copied verbatim"),
            };
            lines.push_str(&format!("<{tier} tier>\n"));
        } else if let Some(layer) = path.strip_prefix(".dx/bazelrc/") {
            let preset = dx_preset::Layer::ALL
                .into_iter()
                .filter(|candidate| candidate.file_name() == layer)
                .flat_map(|candidate| {
                    [false, true].map(|strict| {
                        dx_preset::render_layer_with(candidate, "rules_dx", Some(strict))
                    })
                })
                .find(|preset| text.starts_with(preset.as_str()))
                .expect("an rc starts with its preset");
            lines.push_str(&text[preset.len()..]);
        } else {
            lines.push_str(&text);
        }
    }
    lines
}

fn rendered(inputs: &Inputs) -> BTreeMap<String, Vec<u8>> {
    let once = render(inputs).expect("renders");
    assert_eq!(
        render(inputs).expect("renders"),
        once,
        "rendering is stable"
    );
    once
}

fn case(name: &str) -> Inputs {
    let standard = "schema_version = 1\ntier = \"standard\"\n";
    let strict = "schema_version = 1\ntier = \"strict\"\n";
    match name {
        "standard" => inputs(Some(standard), &["python"], &["ruff.toml"]),
        "strict" => inputs(Some(strict), &["python"], &["ruff.toml"]),
        "no_dx_toml" => inputs(None, &["python", "core"], &[]),
        "existing_exports" => Inputs {
            root_build: Some(RootBuild {
                name: "BUILD".to_owned(),
                text: "exports_files([\"ruff.toml\"])\n".to_owned(),
            }),
            ..inputs(None, &["python", "core"], &["ruff.toml", ".yamlfmt"])
        },
        "no_root_build" => Inputs {
            root_build: None,
            ..inputs(None, &["python"], &["ruff.toml"])
        },
        "mixed_profiles" => inputs(
            Some("schema_version = 1\n[families.python]\ntier = \"strict\"\n"),
            &["python"],
            &["ruff.toml"],
        ),
        "rust" => inputs(
            Some("schema_version = 1\n[families.rust]\ntier = \"strict\"\n"),
            &["rust"],
            &[],
        ),
        _ => panic!("no case {name}"),
    }
}

