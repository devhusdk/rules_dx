#[test]
fn rendered_bazel_files_pass_buildifier() {
    let Ok(buildifier) = std::env::var("DX_BUILDIFIER") else {
        panic!("DX_BUILDIFIER names the pinned buildifier");
    };
    let mut cases = vec![
        inputs(
            None,
            &["python", "rust", "js"],
            &["ruff.toml", "typos.toml"],
        ),
        inputs(
            Some("schema_version = 1\ntier = \"strict\"\n[families.python]\ntier = \"standard\"\n"),
            &["python", "core"],
            &["ruff.toml", ".yamlfmt"],
        ),
    ];
    cases[1].root_build = None;
    let dir = std::env::temp_dir().join(format!("dx_generate_{}", std::process::id()));
    for (index, case) in cases.iter().enumerate() {
        for (path, bytes) in rendered(case) {
            if !path.ends_with(".bazel") {
                continue;
            }
            let file = dir.join(index.to_string()).join(&path);
            std::fs::create_dir_all(file.parent().expect("parent")).expect("mkdir");
            std::fs::write(&file, bytes).expect("write");
            let output = Command::new(&buildifier)
                .args(["--mode=check", "--lint=warn"])
                .arg(&file)
                .output()
                .expect("buildifier runs");
            assert!(
                output.status.success(),
                "{path}: {}{}",
                String::from_utf8_lossy(&output.stdout),
                String::from_utf8_lossy(&output.stderr)
            );
        }
    }
    let _ = std::fs::remove_dir_all(dir);
}

#[test]
fn a_narrower_export_is_an_error() {
    let mut case = inputs(None, &["python"], &["ruff.toml"]);
    case.root_build = Some(RootBuild {
        name: "BUILD".to_owned(),
        text: "exports_files([\"ruff.toml\"], visibility = [\"//tools:__pkg__\"])\n".to_owned(),
    });
    let error = render(&case).expect_err("narrow visibility");
    assert_eq!(
        error,
        GenerateError::NarrowExport {
            build: "BUILD".to_owned(),
            file: "ruff.toml".to_owned(),
            visibility: "//tools:__pkg__".to_owned(),
        }
    );
    assert!(
        error.to_string().contains("add \"//.dx:__pkg__\""),
        "{error}"
    );
}

