import 'dart:convert';
import 'dart:io';

/// Writes `schema.g.dart` from a `schema.json` file.
///
/// Usage: gen_schema SCHEMA_JSON OUTPUT
void main(List<String> arguments) {
  if (arguments.length != 2) {
    stderr.writeln('usage: gen_schema SCHEMA_JSON OUTPUT');
    exit(2);
  }
  final schema = jsonDecode(File(arguments[0]).readAsStringSync()) as Map<String, Object?>;
  final version = schema['version'] as int;
  final fields = (schema['fields'] as List<Object?>).cast<String>();
  final quoted = fields.map((field) => "'$field'").join(', ');
  File(arguments[1]).writeAsStringSync(
    '// Generated by gen_schema. Do not edit.\n'
    'const int schemaVersion = $version;\n'
    'const List<String> schemaFields = <String>[$quoted];\n',
  );
}
