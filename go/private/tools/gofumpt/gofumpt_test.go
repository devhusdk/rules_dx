package gofumpt

import (
	"bytes"
	"errors"
	"os"
	"os/exec"
	"path/filepath"
	"testing"

	"github.com/bazelbuild/rules_go/go/runfiles"
)

var cases = map[string]string{
	"clean.go":   "package a\n\nfunc Add(a, b int) int { return a + b }\n",
	"dirty.go":   "// Package formatdirty is not gofumpt formatted.\npackage formatdirty\n\n// Add returns the sum of a and b.\nfunc Add(a,b int) int{return a+b}\n",
	"imports.go": "package a\n\nimport (\n\t\"example.com/m/b\"\n\t\"os\"\n\t\"github.com/x/y\"\n\t\"fmt\"\n)\n\nvar _ = fmt.Sprint\nvar _ = os.Exit\nvar _ = b.X\nvar _ = y.Y\n",
	"octal.go":   "package a\n\nconst Mode = 0755\n\nvar (\n\tx = 1\n)\n\nfunc F() {\n\n\tprintln(x)\n\n}\n",
	"gen.go":     "// Code generated by hand. DO NOT EDIT.\n\npackage a\n\nvar (\n\tx = 1\n)\n",
	"broken.go":  "package a\n\nfunc {\n",
}

func upstream(t *testing.T) string {
	t.Helper()
	r, err := runfiles.New()
	if err != nil {
		t.Fatal(err)
	}
	path, err := r.Rlocation(os.Getenv("GOFUMPT"))
	if err != nil {
		t.Fatal(err)
	}
	return path
}

func tree(t *testing.T, mod string) string {
	t.Helper()
	dir := t.TempDir()
	if mod != "" {
		if err := os.WriteFile(filepath.Join(dir, "go.mod"), []byte(mod), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	for name, body := range cases {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

type result struct {
	stdout, stderr string
	code           int
	files          map[string]string
}

func runUpstream(t *testing.T, bin, dir string, args []string) result {
	t.Helper()
	cmd := exec.Command(bin, args...)
	cmd.Dir = dir
	var out, errOut bytes.Buffer
	cmd.Stdout, cmd.Stderr = &out, &errOut
	code := 0
	if err := cmd.Run(); err != nil {
		var exit *exec.ExitError
		if !errors.As(err, &exit) {
			t.Fatal(err)
		}
		code = exit.ExitCode()
	}
	return result{out.String(), errOut.String(), code, read(t, dir)}
}

func runMain(t *testing.T, dir string, args []string) result {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	if err := os.Chdir(dir); err != nil {
		t.Fatal(err)
	}
	defer func() {
		if err := os.Chdir(wd); err != nil {
			t.Fatal(err)
		}
	}()
	var out, errOut bytes.Buffer
	code := Main(args, &out, &errOut)
	return result{out.String(), errOut.String(), code, read(t, dir)}
}

func read(t *testing.T, dir string) map[string]string {
	t.Helper()
	files := map[string]string{}
	for name := range cases {
		data, err := os.ReadFile(filepath.Join(dir, name))
		if err != nil {
			t.Fatal(err)
		}
		files[name] = string(data)
	}
	return files
}

func TestMatchesUpstream(t *testing.T) {
	bin := upstream(t)
	mods := map[string]string{
		"no go.mod":     "",
		"module go.mod": "module example.com/m\n\ngo 1.12\n",
	}
	modes := [][]string{
		{"-lang=go1.26", "-d"},
		{"-lang=go1.26", "-l"},
		{"-lang=go1.26", "-w"},
		{"-lang=go1.26"},
		{"-d"},
		{"-lang=go1.26", "-modpath=example.com/m", "-d"},
		{"-lang=go1.26", "-extra", "-d"},
	}
	for modName, mod := range mods {
		for _, flags := range modes {
			for name := range cases {
				args := append(append([]string{}, flags...), name)
				want := runUpstream(t, bin, tree(t, mod), args)
				got := runMain(t, tree(t, mod), args)
				if got.stdout != want.stdout || got.code != want.code || got.files[name] != want.files[name] {
					t.Errorf("%s, %q: got exit %d stdout %q file %q; upstream exit %d stdout %q file %q",
						modName, args, got.code, got.stdout, got.files[name], want.code, want.stdout, want.files[name])
				}
				if (got.stderr == "") != (want.stderr == "") {
					t.Errorf("%s, %q: stderr %q, upstream %q", modName, args, got.stderr, want.stderr)
				}
			}
		}
	}
}

func TestSeveralFilesKeepTheWorstExit(t *testing.T) {
	dir := tree(t, "")
	got := runMain(t, dir, []string{"-lang=go1.26", "-d", "clean.go", "dirty.go", "broken.go"})
	if got.code != 2 {
		t.Errorf("exit %d, want 2 when one file fails to parse", got.code)
	}
}

func TestRejectsNoFiles(t *testing.T) {
	var out, errOut bytes.Buffer
	if code := Main([]string{"-d"}, &out, &errOut); code != 2 {
		t.Errorf("exit %d, want 2 without files", code)
	}
}

func TestRejectsADirectory(t *testing.T) {
	var out, errOut bytes.Buffer
	if code := Main([]string{"-d", t.TempDir()}, &out, &errOut); code != 2 {
		t.Errorf("exit %d, want 2 for a directory", code)
	}
}
