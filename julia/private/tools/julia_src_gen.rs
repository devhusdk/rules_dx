#![deny(clippy::indexing_slicing, clippy::string_slice)]
#![expect(
    clippy::disallowed_methods,
    reason = "runs the flisp the build just compiled, which exits on its own"
)]

use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, ExitCode, Stdio};

fn read(path: &str) -> Result<String, String> {
    fs::read_to_string(path).map_err(|error| format!("read {path}: {error}"))
}

fn write(path: &str, text: &str) -> Result<(), String> {
    fs::write(path, text).map_err(|error| format!("write {path}: {error}"))
}

fn version(text: &str) -> &str {
    text.trim_end_matches(['\n', '\r'])
}

fn version_h(version: &str) -> String {
    let fields: Vec<&str> = version.split(['.', ',', '+', '-']).collect();
    let field = |at: usize| fields.get(at).copied().unwrap_or_default();
    format!(
        "// This is an autogenerated header file\n#ifndef JL_VERSION_H\n#define JL_VERSION_H\n#define JULIA_VERSION_STRING \"{version}\"\n#define JULIA_VERSION_MAJOR {}\n#define JULIA_VERSION_MINOR {}\n#define JULIA_VERSION_PATCH {}\n#define JULIA_VERSION_IS_RELEASE {}\n#endif\n",
        field(0),
        field(1),
        field(2),
        u8::from(fields.len() < 4),
    )
}

fn calls<'a>(line: &'a str, tag: &str) -> impl Iterator<Item = &'a str> + 'a {
    let open = format!("{tag}(");
    let skip = open.len();
    line.rmatch_indices(&open)
        .filter_map(|(at, _)| line.get(at + skip..))
        .collect::<Vec<_>>()
        .into_iter()
}

fn internal_funcs(text: &str) -> String {
    text.lines()
        .filter_map(|line| {
            calls(line, "XX").find_map(|rest| {
                rest.rfind(')')
                    .filter(|&close| close > 0)
                    .and_then(|close| rest.get(..close))
            })
        })
        .map(|name| format!("#define {name} i{name}\n"))
        .collect()
}

fn first_argument<'a>(line: &'a str, tag: &str) -> Option<&'a str> {
    calls(line, tag).find_map(|rest| {
        let comma = rest.find(',').filter(|&comma| comma > 0)?;
        let (name, after) = rest.split_at_checked(comma)?;
        after
            .strip_prefix(", ")
            .filter(|after| after.contains(')'))
            .map(|_| name)
    })
}

fn data_globals(text: &str) -> String {
    [("XX", "sysimg_global."), ("YY", "const_globals.jl")]
        .into_iter()
        .flat_map(|(tag, define)| {
            text.lines()
                .filter(move |line| calls(line, tag).any(|rest| rest.contains(')')))
                .map(move |line| match first_argument(line, tag) {
                    Some(name) => format!("#define jl_{name} ({define}{name})\n"),
                    None => format!("{line}\n"),
                })
        })
        .collect()
}

fn expmap(version: &str, template: &str) -> String {
    let short: Vec<&str> = version.splitn(3, '.').take(2).collect();
    let libjulia = format!("JL_LIBJULIA_{}", short.join("."));
    template
        .lines()
        .map(|line| {
            let line = line
                .replacen("@JULIA_SHLIB_SYMBOL_VERSION@", &libjulia, 1)
                .replacen("@LLVM_SHLIB_SYMBOL_VERSION@", "JL_LLVM_20.1", 1);
            format!("{line}\n")
        })
        .collect()
}

enum Io<'a> {
    Filter(&'a str),
    Boot(&'a str),
}

fn flisp(exe: &str, boot: &str, script: &str, io: &Io, out: &str) -> Result<(), String> {
    let work = PathBuf::from(format!("{out}.flisp"));
    fs::create_dir_all(&work).map_err(|error| format!("create {}: {error}", work.display()))?;
    let result = run_flisp(&work, exe, boot, script, io, out);
    let cleanup =
        fs::remove_dir_all(&work).map_err(|error| format!("remove {}: {error}", work.display()));
    result.and(cleanup)
}

fn run_flisp(
    work: &Path,
    exe: &str,
    boot: &str,
    script: &str,
    io: &Io,
    out: &str,
) -> Result<(), String> {
    let copy = work.join("flisp");
    fs::copy(exe, &copy).map_err(|error| format!("copy {exe}: {error}"))?;
    fs::copy(boot, work.join("flisp.boot")).map_err(|error| format!("copy {boot}: {error}"))?;
    let mut command = Command::new(&copy);
    command.arg(script);
    match io {
        Io::Filter(input) => {
            let input = fs::File::open(input).map_err(|error| format!("open {input}: {error}"))?;
            let output = fs::File::create(out).map_err(|error| format!("create {out}: {error}"))?;
            command.stdin(input).stdout(output);
        }
        Io::Boot(entry) => {
            let entry = Path::new(entry);
            let dir = entry.parent().unwrap_or_else(|| Path::new("."));
            let name = entry
                .file_name()
                .ok_or_else(|| format!("{} names no file", entry.display()))?;
            let out =
                std::path::absolute(out).map_err(|error| format!("absolute {out}: {error}"))?;
            command.arg(dir).arg(name).arg(out).stdin(Stdio::null());
        }
    }
    let status = command
        .status()
        .map_err(|error| format!("run flisp: {error}"))?;
    if status.success() {
        Ok(())
    } else {
        Err(format!("flisp {script} failed: {status}"))
    }
}

fn run(args: &[String]) -> Result<(), String> {
    let words: Vec<&str> = args.iter().map(String::as_str).collect();
    match words.as_slice() {
        ["version-h", version_file, out] => write(out, &version_h(version(&read(version_file)?))),
        ["internal-funcs", input, out] => write(out, &internal_funcs(&read(input)?)),
        ["data-globals", input, out] => write(out, &data_globals(&read(input)?)),
        ["expmap", version_file, template, out] => write(
            out,
            &expmap(version(&read(version_file)?), &read(template)?),
        ),
        ["flisp-boot", exe, boot, script, entry, out] => {
            flisp(exe, boot, script, &Io::Boot(entry), out)
        }
        ["flisp-filter", exe, boot, script, input, out] => {
            flisp(exe, boot, script, &Io::Filter(input), out)
        }
        _ => Err(format!(
            "usage: julia_src_gen version-h VERSION OUT | internal-funcs IN OUT | data-globals IN OUT | expmap VERSION IN OUT | flisp-boot FLISP BOOT SCRIPT ENTRY OUT | flisp-filter FLISP BOOT SCRIPT IN OUT; got {}",
            words.join(" ")
        )),
    }
}

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match run(&args) {
        Ok(()) => ExitCode::SUCCESS,
        Err(error) => {
            eprintln!("julia_src_gen: {error}");
            ExitCode::FAILURE
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_version_header_marks_a_plain_version_as_a_release() {
        let header = version_h("1.13.4");
        assert!(header.contains("#define JULIA_VERSION_STRING \"1.13.4\"\n"));
        assert!(header.contains("#define JULIA_VERSION_MAJOR 1\n#define JULIA_VERSION_MINOR 13\n#define JULIA_VERSION_PATCH 4\n"));
        assert!(header.contains("#define JULIA_VERSION_IS_RELEASE 1\n"));
        assert!(version_h("1.14.0-DEV").contains("#define JULIA_VERSION_IS_RELEASE 0\n"));
    }

    #[test]
    fn internal_funcs_rename_each_exported_function() {
        let text = "#define JL_EXPORTED_FUNCS(XX) \\\n    XX(jl_alloc_array_1d) \\\n    XX(jl_gc_alloc) \\\nother\n";
        assert_eq!(
            internal_funcs(text),
            "#define jl_alloc_array_1d ijl_alloc_array_1d\n#define jl_gc_alloc ijl_gc_alloc\n"
        );
    }

    #[test]
    fn data_globals_list_every_xx_before_every_yy() {
        let text = "    YY(one, jl_value_t*) \\\n    XX(abstractarray_type, jl_unionall_t*) \\\n    XX(odd) \\\n";
        assert_eq!(
            data_globals(text),
            "#define jl_abstractarray_type (sysimg_global.abstractarray_type)\n    XX(odd) \\\n#define jl_one (const_globals.jlone)\n"
        );
    }

    #[test]
    fn the_expmap_names_the_major_minor_symbol_version() {
        assert_eq!(
            expmap(
                "1.13.4",
                "@JULIA_SHLIB_SYMBOL_VERSION@ {\n@LLVM_SHLIB_SYMBOL_VERSION@ {\n"
            ),
            "JL_LIBJULIA_1.13 {\nJL_LLVM_20.1 {\n"
        );
    }
}
