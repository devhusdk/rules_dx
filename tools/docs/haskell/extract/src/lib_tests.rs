use super::*;

const HOOGLE: &str = "-- Hoogle documentation, generated by Haddock\n\n@package geometry\n@version 0.1\n\nmodule Geometry\n-- | Geometry helpers.\n-- | A circle.\ndata Circle\nCircle :: Double -> Circle\n-- | The radius.\n[radius] :: Circle -> Double\n-- | Things that have an area.\n--   Second line.\nclass Area a\n-- | The area.\nareaOf :: Area a => a -> Double\n-- | Area of a circle.\narea :: Circle -> Double\n(<+>) :: Circle -> Circle -> Circle\ntype Radius = Double\ninstance Geometry.Area Geometry.Circle\n";

const SOURCE: &str = "module Geometry where\n\ndata Circle = Circle\n  { radius :: Double\n  }\n\nclass Area a where\n  areaOf :: a -> Double\n\narea :: Circle -> Double\narea = undefined\n(<+>) :: Circle -> Circle -> Circle\n(<+>) = const\ntype Radius = Double\n";

fn shard(config: &str) -> DocIr {
    let sources = vec![Source {
        exec_path: "src/Geometry.hs".to_owned(),
        rel: "geometry/src/Geometry.hs".to_owned(),
        generated: false,
    }];
    let mut texts = BTreeMap::new();
    texts.insert("src/Geometry.hs".to_owned(), SOURCE.to_owned());
    convert(HOOGLE, &sources, &texts, "geometry", config).expect("converts")
}

fn find<'a>(shard: &'a DocIr, id: &str) -> &'a Symbol {
    shard
        .symbols
        .iter()
        .find(|s| s.id == format!("haskell:geometry:{id}"))
        .unwrap_or_else(|| panic!("no {id} in {:?}", shard.symbols.iter().map(|s| &s.id).collect::<Vec<_>>()))
}

#[test]
fn ids_kinds_and_instances_dropped() {
    let shard = shard("");
    let ids: Vec<&str> = shard.symbols.iter().map(|s| s.id.as_str()).collect();
    assert_eq!(ids.len(), 9, "{ids:?}");
    assert_eq!(find(&shard, "Geometry").kind, SymbolKind::Module as i32);
    assert_eq!(find(&shard, "Geometry.Circle").kind, SymbolKind::Class as i32);
    assert_eq!(find(&shard, "Geometry.Circle.Circle").kind, SymbolKind::EnumVariant as i32);
    assert_eq!(find(&shard, "Geometry.Circle.radius").kind, SymbolKind::Field as i32);
    assert_eq!(find(&shard, "Geometry.Area").kind, SymbolKind::Interface as i32);
    assert_eq!(find(&shard, "Geometry.Area.areaOf").kind, SymbolKind::Method as i32);
    assert_eq!(find(&shard, "Geometry.area").kind, SymbolKind::Function as i32);
    assert_eq!(find(&shard, "Geometry.Radius").kind, SymbolKind::TypeAlias as i32);
    assert!(!ids.iter().any(|id| id.contains("instance")));
}

#[test]
fn docs_signatures_and_positions() {
    let shard = shard("x");
    assert_eq!(find(&shard, "Geometry.Area").doc_markdown, "Things that have an area.\nSecond line.");
    assert_eq!(find(&shard, "Geometry.Circle.radius").doc_markdown, "The radius.");
    assert_eq!(find(&shard, "Geometry.area").signature_text, "area :: Circle -> Double");
    let line = |id: &str| find(&shard, id).source.as_ref().expect("source").line;
    assert_eq!(line("Geometry.Circle"), 3);
    assert_eq!(line("Geometry.Circle.radius"), 4);
    assert_eq!(line("Geometry.Area.areaOf"), 8);
    assert_eq!(line("Geometry.area"), 10);
    assert_eq!(find(&shard, "Geometry.area").source.as_ref().expect("source").file, "geometry/src/Geometry.hs");
    assert_eq!(find(&shard, "Geometry").extensions[0].value, b"hoogle=1;package=geometry;config=x");
}

#[test]
fn unknown_module_file_is_rejected() {
    let error = convert(HOOGLE, &[], &BTreeMap::new(), "geometry", "").expect_err("rejected");
    assert!(error.contains("not in the srcs manifest"), "{error}");
}

#[test]
fn parse_rejects_bad_arguments() {
    let args = |list: &[&str]| list.iter().map(|s| (*s).to_owned()).collect::<Vec<_>>();
    assert!(parse(&args(&["--nope", "x"])).is_err());
    assert!(parse(&args(&["--hoogle", "a"])).is_err());
    let all = args(&["--hoogle", "a", "--sources", "s", "--out", "o", "--package", "p"]);
    assert_eq!(parse(&all).expect("parses").package, "p");
}
